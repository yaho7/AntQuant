import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Download, ExternalLink, ScrollText, Square } from "lucide-react";
import * as React from "react";
import { Link, useParams } from "react-router-dom";
import { TimeSeriesChart } from "@/components/charts/TimeSeriesChart";
import { EmptyState, ErrorState, LoadingState, PageHeader, QueryBoundary, StatusBadge } from "@/components/common";
import { MetricsGrid } from "@/components/MetricsGrid";
import { useToast } from "@/components/toast";
import { Button } from "@/components/ui/button";
import { Alert, Card, CardContent, CardHeader, CardTitle, Table, Td, Th } from "@/components/ui/primitives";
import { between, dateTime, duration, money, num } from "@/lib/format";
import { api } from "@/services/api";
import type { Backtest, BacktestResult } from "@/types/api";
import { Progress } from "./BacktestingPage";
import { t } from "@/lib/i18n";

const NATIVE_FILES: { kind: string; label: string; open?: boolean }[] = [
  { kind: "tearsheet_html", label: "Tearsheet (HTML)", open: true },
  { kind: "plot_html", label: "Trades chart (HTML)", open: true },
  { kind: "indicators_html", label: "Indicators (HTML)", open: true },
  { kind: "trades", label: "LumiBot trades.csv" },
  { kind: "stats", label: "LumiBot stats.csv" },
  { kind: "tearsheet_csv", label: "Tearsheet metrics (CSV)" },
  { kind: "tearsheet_metrics", label: "Tearsheet metrics (JSON)" },
  { kind: "settings", label: "Run settings (JSON)" },
];

function Report({ id }: { id: string }) {
  const result = useQuery({
    queryKey: ["backtest", id, "result"],
    queryFn: () => api.get<BacktestResult>(`/api/backtests/${id}/result`),
    staleTime: Infinity,
  });
  const equity = React.useMemo(
    () => [{ name: t("Portfolio value"), color: "--chart-1", data: result.data?.equity_curve ?? [] }],
    [result.data],
  );
  const drawdown = React.useMemo(
    () => [{ name: t("Drawdown"), color: "--loss", data: result.data?.drawdown_curve ?? [] }],
    [result.data],
  );
  if (result.isLoading) return <LoadingState rows={8} />;
  if (result.error) return <ErrorState error={result.error} onRetry={() => result.refetch()} />;
  const r = result.data!;
  return (
    <div className="grid gap-4">
      <MetricsGrid metrics={r.metrics} notes={r.notes} />
      <Card>
        <CardHeader><CardTitle>{t("Equity curve")}</CardTitle></CardHeader>
        <CardContent>
          {r.equity_curve.length < 2 ? <EmptyState title={t("No equity data")} /> : <TimeSeriesChart series={equity} />}
        </CardContent>
      </Card>
      <Card>
        <CardHeader><CardTitle>{t("Drawdown")}</CardTitle></CardHeader>
        <CardContent>
          {r.drawdown_curve.length < 2 ? <EmptyState title={t("No drawdown data")} /> : <TimeSeriesChart series={drawdown} format="pct" height={200} />}
        </CardContent>
      </Card>
      <Card>
        <CardHeader>
          <CardTitle>{t("Trade history")}</CardTitle>
          <div className="flex gap-2">
            <Button asChild size="sm" variant="outline"><a href={`/api/backtests/${id}/export/trades.csv`}><Download /> {t("Trades CSV")}</a></Button>
            <Button asChild size="sm" variant="outline"><a href={`/api/backtests/${id}/export/equity.csv`}><Download /> {t("Equity CSV")}</a></Button>
          </div>
        </CardHeader>
        <CardContent className="px-0">
          <TradesTable trades={r.trades} />
        </CardContent>
      </Card>
      <Card>
        <CardHeader>
          <div>
            <CardTitle>{t("LumiBot native reports")}</CardTitle>
            <p className="mt-1 text-xs text-muted-foreground">{t("Files generated by LumiBot for this run.")}</p>
          </div>
        </CardHeader>
        <CardContent className="flex flex-wrap gap-2">
          {NATIVE_FILES.filter((f) => r.files[f.kind]).map((f) => (
            <Button key={f.kind} asChild size="sm" variant="outline">
              <a href={`/api/backtests/${id}/files/${f.kind}`} target={f.open ? "_blank" : undefined} rel="noreferrer">
                {f.open ? <ExternalLink /> : <Download />} {t(f.label)}
              </a>
            </Button>
          ))}
          {NATIVE_FILES.every((f) => !r.files[f.kind]) && <p className="text-sm text-muted-foreground">{t("No native files were produced.")}</p>}
        </CardContent>
      </Card>
    </div>
  );
}

function TradesTable({ trades }: { trades: BacktestResult["trades"] }) {
  const [limit, setLimit] = React.useState(100);
  if (trades.length === 0) return <EmptyState title={t("The strategy made no trades")} />;
  return (
    <>
      <Table>
        <thead><tr><Th>{t("Time")}</Th><Th>{t("Symbol")}</Th><Th>{t("Side")}</Th><Th>{t("Type")}</Th><Th className="text-right">{t("Qty")}</Th><Th className="text-right">{t("Price")}</Th><Th className="text-right">{t("Value")}</Th><Th className="text-right">{t("Fee")}</Th></tr></thead>
        <tbody>
          {trades.slice(0, limit).map((tr, i) => (
            <tr key={i}>
              <Td className="num text-xs" title={t("Exchange time")}>{tr.time.slice(0, 16)}</Td>
              <Td className="font-medium">{tr.symbol}</Td>
              <Td className="capitalize">{t(tr.side.toLowerCase())}</Td>
              <Td className="capitalize text-xs">{tr.order_type ? t(tr.order_type.toLowerCase().replace(/_/g, " ")) : "—"}</Td>
              <Td className="num text-right">{num(tr.quantity, 4)}</Td>
              <Td className="num text-right">{money(tr.price)}</Td>
              <Td className="num text-right">{money(tr.quantity * tr.price * (tr.multiplier ?? 1))}</Td>
              <Td className="num text-right">{money(tr.fee)}</Td>
            </tr>
          ))}
        </tbody>
      </Table>
      {trades.length > limit && (
        <div className="flex justify-center p-3">
          <Button size="sm" variant="ghost" onClick={() => setLimit((l) => l + 200)}>
            {t("Show more ({n} remaining)", { n: trades.length - limit })}
          </Button>
        </div>
      )}
    </>
  );
}

export function BacktestReportPage() {
  const { id = "" } = useParams();
  const qc = useQueryClient();
  const toast = useToast();
  const task = useQuery({
    queryKey: ["backtest", id],
    queryFn: () => api.get<Backtest>(`/api/backtests/${id}`),
    refetchInterval: (q) =>
      q.state.data && ["pending", "starting", "running"].includes(q.state.data.status) ? 2000 : false,
  });
  const stop = useMutation({
    mutationFn: () => api.post(`/api/backtests/${id}/stop`),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ["backtest", id] });
      toast.success("Stop requested");
    },
    onError: toast.error,
  });
  return (
    <QueryBoundary query={task} rows={6}>
      {(b) => {
        const active = ["pending", "starting", "running"].includes(b.status);
        return (
          <>
            <PageHeader
              title={`${t("Backtest")} · ${b.strategy_name}`}
              description={
                <span className="num">
                  {String(b.config.start)} → {String(b.config.end)} · {money(Number(b.config.budget), "USD", 0)} ·{" "}
                  {String(b.config.data_source)}{b.strategy_version != null && ` · ${t("Strategy v{v}", { v: b.strategy_version })}`}
                </span>
              }
              actions={
                <>
                  <Button asChild variant="outline" size="sm"><Link to={`/logs?source=task:${b.id}`}><ScrollText /> {t("Log")}</Link></Button>
                  {active && <Button variant="outline" size="sm" loading={stop.isPending} onClick={() => stop.mutate()}><Square /> {t("Stop")}</Button>}
                </>
              }
            />
            <Card className="mb-4 flex flex-wrap items-center gap-x-6 gap-y-2 p-4 text-sm">
              <StatusBadge status={b.status} />
              {active && (
                <span className="flex items-center gap-2">
                  <Progress value={b.progress} />
                  <span className="num text-muted-foreground">{b.progress != null ? `${b.progress.toFixed(1)}%` : t("Waiting for first progress update")}</span>
                </span>
              )}
              <span className="text-muted-foreground">{t("Started")} <span className="num text-foreground">{dateTime(b.started_at)}</span></span>
              <span className="text-muted-foreground">{t("Duration")} <span className="num text-foreground">{b.started_at ? duration(between(b.started_at, b.ended_at)) : "—"}</span></span>
              <span className="text-muted-foreground">{t("Benchmark")} <span className="text-foreground">{b.config.benchmark ? String(b.config.benchmark) : t("None")}</span></span>
            </Card>
            {b.status === "failed" && <Alert tone="loss" className="mb-4"><div><b>{t("Backtest failed.")}</b> {b.error_message && t(b.error_message)}</div></Alert>}
            {b.status === "stopped" && <Alert tone="warning" className="mb-4">{t(b.error_message ?? "Stopped.")}</Alert>}
            {b.status === "completed" ? (
              <Report id={b.id} />
            ) : active ? (
              <Card><EmptyState title={t("Backtest is running")} description={t("Results appear here when it finishes. Data download for the first run can take a few minutes.")} /></Card>
            ) : null}
          </>
        );
      }}
    </QueryBoundary>
  );
}
